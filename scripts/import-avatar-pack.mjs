// Import avatar-pack exports into personality-avatars-data.ts
// Usage: node scripts/import-avatar-pack.mjs [path-to-avatar-pack/exports]
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const DEFAULT_SRC = resolve(import.meta.dirname, "../data/avatar-pack");
const SRC = resolve(process.argv[2] ?? DEFAULT_SRC);
const SVG_DIR = join(SRC, "svgs");
const MANIFEST = join(SRC, "manifest.json");
const OUT = "src/app/_components/personality-avatars-data.ts";

const BANNED = ["<defs", " id=", "<text", "<style", "<image", "<script", "url("];

const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
const map = {};
let rejected = 0;

for (const entry of manifest) {
  const file = join(SVG_DIR, `${entry.key}.svg`);
  let svg;
  try {
    svg = readFileSync(file, "utf8").trim();
  } catch {
    console.warn(`Missing SVG: ${entry.key}`);
    rejected++;
    continue;
  }
  if (!svg.startsWith("<svg") || !svg.includes("viewBox")) {
    rejected++;
    continue;
  }
  const lower = svg.toLowerCase();
  if (BANNED.some((b) => lower.includes(b))) {
    rejected++;
    continue;
  }
  if (!/<svg[^>]*\bwidth=/.test(svg)) {
    svg = svg.replace("<svg", '<svg width="100%" height="100%"');
  }
  map[entry.key] = svg;
}

const list = manifest.filter((entry) => map[entry.key]).map(({ key, label }) => ({ key, label }));

const header = `// AUTO-GENERATED by scripts/import-avatar-pack.mjs - do not edit by hand.
// ${list.length} original SVG character avatars for personalities.

export const PERSONALITY_AVATARS = ${JSON.stringify(list, null, 2)} as const;

export type PersonalityAvatarKey = (typeof PERSONALITY_AVATARS)[number]["key"];

export const DEFAULT_AVATAR_KEY = ${JSON.stringify(list[0]?.key ?? "mutant-01")};

export const AVATAR_SVGS: Record<string, string> = ${JSON.stringify(map, null, 2)};
`;

writeFileSync(OUT, header);
console.log(`Wrote ${list.length} avatars to ${OUT} (rejected ${rejected}).`);
